-- Schema v16: the `review_comments` table (v2.4 — Diff et review locale, Phase 4, task
-- 01KX0F6HEBPK34CV49EREHK3Y9 — "Modèle comment + ancrage + re-mapping + outdated").
--
-- ## Why ONE auto-threaded table (PDR-0012 / PDR-0015)
--
-- The review is a VUE DÉRIVÉE (PDR-0015): there is NO stored `review` / `thread` /
-- `message` / `finding` entity. A comment is the ONLY persisted review artifact — it
-- anchors on `(workspace, repository)` (+ an optional `spec_id`) and threads on ITSELF via
-- `parent_id` (NULL = a thread ROOT, non-NULL = a reply under that root). The threads and
-- messages tables of the old model collapse into this single table (the proto's
-- `types.ts::ReviewComment` traced to `data-model.dbml`). `finding = task`, so there is
-- deliberately NO `review_findings` table (a promoted comment becomes a coder task — a
-- `review_tasks` row — in a later phase, not a row here).
--
-- ## Anchoring + re-mapping + outdated
--
-- An ANCHORED comment records where on the diff it hangs: `file_path` + `side`
-- (old|new) + `line_start`/`line_end` (a single line or a range), plus the material the
-- RE-MAPPING needs to survive a new commit — the `blob` SHA it was captured on, the
-- `snippet` (the anchored line text) and the surrounding `context` (a few lines around it).
-- When the repo advances (a new commit / checkout), the re-mapping relocates the snippet
-- inside the fresh blob; if it can no longer be located reliably, the comment flips
-- `outdated = 1`. A GLOBAL comment has `file_path` NULL (no anchor, never outdated).
--
-- ## Resolution reserved to the human
--
-- `status` is `open` | `resolved`; `resolved_by_type` records WHO resolved it. The human
-- is the ONLY actor allowed to set `resolved` — enforced in the use-case layer AND at the
-- MCP façade (the agent tool set has post/reply but NO resolve). The agent may only REPLY
-- (a new row with `parent_id`), never resolve.
--
-- ## Author human OR agent
--
-- `author_type` is `human` | `agent` (CHECK-enforced), `author_name` the display name.
-- Both façades write the same table; only the *resolution* capability differs by actor.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the
-- Rust layer, with a portable julianday DEFAULT as a raw-insert safety net.

CREATE TABLE review_comments (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id                TEXT    NOT NULL PRIMARY KEY,

    -- The (workspace, repository) the comment anchors on. Plain correlation columns (no FK
    -- CASCADE): the review is a derived view and a comment must survive Git churn / a
    -- workspace archive the same way `domain_events` survives a delete. `spec_id` is the
    -- OPTIONAL spec the review is bound to (NULL = generic review, PDR-0004).
    workspace_id      TEXT    NOT NULL,
    repository_id     TEXT    NOT NULL,
    spec_id           TEXT,

    -- Thread self-reference: NULL = a thread ROOT; non-NULL = a reply under that root.
    -- ON DELETE CASCADE so deleting a root removes its replies (a reply has no meaning
    -- without its root). Auto-threading is the WHOLE threading model (no separate table).
    parent_id         TEXT    REFERENCES review_comments(id) ON DELETE CASCADE,

    -- WHO authored it. CHECK-enforced to the two review actors.
    author_type       TEXT    NOT NULL CHECK (author_type IN ('human', 'agent')),
    author_name       TEXT    NOT NULL,

    -- ── Anchor (all NULL for a GLOBAL comment) ───────────────────────────────
    -- The repo-prefixed changed-file path the comment hangs on (NULL = global).
    file_path         TEXT,
    -- Which diff side the anchor is on: 'old' (removed/base) | 'new' (added/target).
    side              TEXT    CHECK (side IN ('old', 'new')),
    -- 1-based anchored line (or range start) on `side`.
    line_start        INTEGER,
    -- 1-based range end on `side` (equals `line_start` for a single-line anchor).
    line_end          INTEGER,
    -- The blob SHA the anchor was captured on (the re-mapping's starting point).
    blob              TEXT,
    -- The anchored line text (the primary snippet the re-mapping relocates).
    snippet           TEXT,
    -- The surrounding lines (a few before/after) — the re-mapping's disambiguation context.
    context           TEXT,

    -- `1` when the anchor could no longer be relocated after the repo advanced (the
    -- snippet/context no longer maps into the fresh blob). A GLOBAL comment is never outdated.
    outdated          INTEGER NOT NULL DEFAULT 0,

    -- The comment text.
    body              TEXT    NOT NULL,

    -- Lifecycle: 'open' until a HUMAN resolves it → 'resolved'. Only the human may resolve.
    status            TEXT    NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
    -- WHO resolved it (NULL while open). Only ever 'human' by policy; CHECK keeps the column
    -- honest for either actor value while the app enforces human-only at the write path.
    resolved_by_type  TEXT    CHECK (resolved_by_type IN ('human', 'agent')),

    created_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The common read: "the comments of this (workspace, repository)" (the review panel's
-- whole feed). Ordered scans key on created_at at the query layer.
CREATE INDEX idx_review_comments_repo ON review_comments (workspace_id, repository_id);

-- The thread expansion: "the replies of this root". Partial (only rows that actually carry
-- a parent participate).
CREATE INDEX idx_review_comments_parent ON review_comments (parent_id)
    WHERE parent_id IS NOT NULL;
