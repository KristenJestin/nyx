-- Schema v26: the IDEAS domain — `ideas` + `idea_specs` (M2M) + an FTS5 index
-- (v2.6 — Idées entretenues, annexes & dépendances Spec, Phase 1, task
-- 01KXZ9K1ETEBFTR9NNYZVKHCE9 — "Modèle idées : ideas + idea_specs (M2M, kind
-- addresses/related) + FTS5 + statuts").
--
-- ## Why this domain (the ENTRETIEN backlog, PRD Impl Decisions)
--
-- Depot's « idées » entity is a write-only cimetière (~91 open for 1 promoted): nothing
-- closes, nothing dedups, nothing surfaces at the right moment. v2.6 rapatriates the memory
-- natively and refounds the core around MAINTENANCE, not storage. This migration lays the
-- persistence floor the MCP tools (task 2) and the later lifecycle/UI phases build on:
--
--   * `ideas` — the backlog entity itself, with a MAINTAINED lifecycle (`status`), a `theme`
--     for the by-theme grouping, a capture `source`, and the `closed_at`/`closed_reason`
--     fermeture trail.
--   * `idea_specs` — the MANY-TO-MANY idée↔Spec link, with a `kind` that materializes the
--     resolution (`addresses` = the Spec traite l'idée / `related` = contexte seul). The
--     kind is what the auto lifecycle (Phase 2) keys on — only `addresses` links drive a
--     status change; `related` links never do.
--   * an FTS5 index on (title, body) — the substrate the `idea_search` MCP tool (task 2)
--     scores its top-N over (FTS5 + a Rust fuzzy pass), so the agent SURFACES the relevant
--     slice instead of dumping a flat list.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the
-- Rust backend on every write, with the portable julianday DEFAULT as a raw-insert safety net.

-- --- ideas: the maintained backlog entity ------------------------------------

CREATE TABLE ideas (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id             TEXT    NOT NULL PRIMARY KEY,

    -- The project the idea belongs to. ON DELETE CASCADE: removing a project removes its
    -- ideas (an idea has no meaning without its project), like `specs`.
    project_id     TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The idea itself: a short `title` and a longer `body` (both FTS5-indexed below).
    title          TEXT    NOT NULL,
    body           TEXT    NOT NULL DEFAULT '',

    -- Lifecycle (the missing piece of Depot). `open` (fresh backlog), `planned` (a linked
    -- Spec went in_progress — Phase 2), `implemented` (resolved — closed with a motif), or
    -- `dropped` (abandoned). The auto transitions (Phase 2) are GUARDED in the backend; this
    -- migration stores the value with the `open` default and its CHECK vocabulary.
    status         TEXT    NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'planned', 'implemented', 'dropped')),

    -- The grouping axis for the by-theme Idées view (nullable = ungrouped). Free-text.
    theme          TEXT,

    -- How the idea was captured: `session` (an agent raised it during dev/review/nspec — the
    -- common case), `spec` (derived from a Spec), or `manual` (a human typed it). Default
    -- `session`: the MCP `idea_add` capture path is the agent working.
    source         TEXT    NOT NULL DEFAULT 'session'
        CHECK (source IN ('session', 'spec', 'manual')),

    created_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- Fermeture trail (both NULL while the idea is live): WHEN it closed (epoch ms) and the
    -- motif ("implémentée via Spec X", "merged into <id>", a fermeture-par-constat reason, …).
    closed_at      INTEGER,
    closed_reason  TEXT
);

-- The board/list read is per project, grouped by theme then recency — index the scan keys.
CREATE INDEX idx_ideas_project_status ON ideas (project_id, status);
CREATE INDEX idx_ideas_project_theme ON ideas (project_id, theme);

-- --- idea_specs: the many-to-many idée↔Spec link -----------------------------

CREATE TABLE idea_specs (
    -- The idea side (FK → ideas). ON DELETE CASCADE: dropping an idea drops its links.
    idea_id     TEXT    NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,

    -- The Spec side (FK → specs). ON DELETE CASCADE: a deleted Spec drops out of every
    -- idea's link set (no dangling link to a Spec that no longer exists).
    spec_id     TEXT    NOT NULL REFERENCES specs(id) ON DELETE CASCADE,

    -- The relationship kind: `addresses` = the Spec traite l'idée (the resolution/promotion
    -- link the auto lifecycle keys on) or `related` = contexte seul (never drives a status
    -- change). CHECK-enforced.
    kind        TEXT    NOT NULL DEFAULT 'addresses'
        CHECK (kind IN ('addresses', 'related')),

    created_at  INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- The (idea, spec) pair is the PRIMARY KEY: a Spec is linked to an idea AT MOST ONCE.
    -- Re-linking an already-linked pair UPDATES the kind (the backend `link_idea_spec` uses
    -- an upsert — idempotent, never a duplicate row).
    PRIMARY KEY (idea_id, spec_id)
);

-- Reverse-lookup index: "which ideas does THIS Spec address / relate to" — the query the
-- auto lifecycle (Phase 2) and the Spec-detail "idées liées" (Phase 4) run. The forward
-- direction ("the links of an idea") is served by the composite PRIMARY KEY prefix.
CREATE INDEX idx_idea_specs_spec ON idea_specs (spec_id);

-- --- ideas_fts: the FTS5 full-text index on (title, body) ---------------------
--
-- EXTERNAL-CONTENT FTS5 (`content='ideas'`): the index stores only the tokenized terms and
-- reads the column text back from `ideas` via the implicit integer `rowid` (content_rowid
-- defaults to `rowid`). This is the canonical, robust FTS5 pattern for a table whose primary
-- key is a TEXT UUID (the UUID cannot be an FTS rowid, but the implicit rowid can). The
-- `idea_search` tool joins `ideas.rowid = ideas_fts.rowid` to map a hit back to its idea id
-- and scores with `bm25(ideas_fts)`.
CREATE VIRTUAL TABLE ideas_fts USING fts5(
    title,
    body,
    content='ideas',
    content_rowid='rowid'
);

-- Keep the FTS index in sync with `ideas` via triggers (the standard external-content sync).
-- INSERT feeds the new row's terms; DELETE and UPDATE issue the FTS5 'delete' command with
-- the OLD values so the right terms are removed before the new ones are (re)indexed. Every
-- idea write path (the Rust CRUD, a merge, a future UI edit) stays consistent for free.
CREATE TRIGGER ideas_fts_ai AFTER INSERT ON ideas BEGIN
    INSERT INTO ideas_fts (rowid, title, body) VALUES (new.rowid, new.title, new.body);
END;

CREATE TRIGGER ideas_fts_ad AFTER DELETE ON ideas BEGIN
    INSERT INTO ideas_fts (ideas_fts, rowid, title, body) VALUES ('delete', old.rowid, old.title, old.body);
END;

CREATE TRIGGER ideas_fts_au AFTER UPDATE ON ideas BEGIN
    INSERT INTO ideas_fts (ideas_fts, rowid, title, body) VALUES ('delete', old.rowid, old.title, old.body);
    INSERT INTO ideas_fts (rowid, title, body) VALUES (new.rowid, new.title, new.body);
END;
