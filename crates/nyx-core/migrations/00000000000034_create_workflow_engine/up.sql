-- Schema v34: the ORCHESTRATION ENGINE domain — `workflows` + `nodes` + `workflow_runs`
-- (v2.8 — Harnais : moteur d'orchestration behavior tree, Phase 2, task
-- 01KY71HZFPKW0P1ZRDVXXBRBGS — "Schéma DB : workflows + nodes typés + workflow_runs
-- (blackboard)").
--
-- ## Why this domain (the PRD's "Orchestration = donnée")
--
-- v2.8 stops holding the dev PROCESS in an orchestrator agent's head (prose it must follow)
-- and stores it as a DETERMINISTIC BEHAVIOR TREE nyx interprets itself. This migration is the
-- persistence floor: the graph is DATA (a tree of typed nodes), and a run is the live cursor +
-- blackboard nyx advances. The interpreter (task T3) and the `nyx_next` verb (T4) build on it.
--
--   * `workflows` — one behavior tree. `project_id` NULL = a BUILT-IN nyx default (the seeded
--     ndev / nspec / ndoc flows), non-NULL = a project's own (forked/customised) flow. `scope`
--     names which flow it is (ndev/nspec/ndoc/custom). `root_node_id` points at the tree's ROOT
--     node (set AFTER the nodes are inserted — NULL for an empty draft). `forked_from` is the
--     provenance link to the workflow this one was forked from (SET NULL if that source is
--     deleted — a fork outlives its origin).
--   * `nodes` — the tree itself, PURE (parent_id + order_index), no out-of-tree FSM edges in v1
--     (PRD OUT: "Sauts FSM explicites → v1 = arbre pur"). A node is TYPED (`type`, an enum:
--     the 3 composites + the 8 leaves of the PRD model) and carries a `config` JSON blob typed
--     PER node kind (spawn→{agent_id}, gate→{command_ids,blocking}, transition→{target_state},
--     judge→{prompt,output_schema}, loop→{until}, selector→{branches:[{cond,child}]},
--     note→{text}, …). The tree is RECONSTRUCTIBLE from the rows alone: root = the workflow's
--     `root_node_id` (or the node whose `parent_id` IS NULL); a composite's ORDERED children =
--     the rows with `parent_id = <it>` sorted by `order_index`.
--   * `workflow_runs` — one live execution. `spec_id` (nullable) ties the run to the Spec it
--     drives; `current_node_id` is the cursor (the node the run is parked on); `blackboard` is
--     the run's JSON scratchpad (last gate verdict, phase index, findings count, last diff, …);
--     `status` is the run lifecycle; `started_at` stamps the launch.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the Rust
-- backend on every write, with the portable julianday DEFAULT as a raw-insert safety net.

-- --- workflows: one stored behavior tree ------------------------------------
--
-- NOTE ON THE FORWARD FK: `root_node_id` references `nodes(id)`, a table created BELOW.
-- SQLite resolves a foreign key's parent table lazily (at INSERT/enforcement time, not at
-- CREATE TABLE time), so declaring the reference before `nodes` exists is valid — and it is
-- populated only after the root node row is inserted (a create-nodes-then-set-root sequence).
CREATE TABLE workflows (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id             TEXT    NOT NULL PRIMARY KEY,

    -- The owning project, or NULL for a BUILT-IN nyx default flow (the seeded ndev/nspec/ndoc).
    -- ON DELETE CASCADE: removing a project removes its own workflows; the NULL-project
    -- built-ins are never touched (no project owns them).
    project_id     TEXT    REFERENCES projects(id) ON DELETE CASCADE,

    -- Human name of the workflow.
    name           TEXT    NOT NULL,

    -- Which flow this tree IS: ndev (the dev loop), nspec (spec authoring), ndoc (doc-sync), or
    -- custom (a project-authored graph). Free-ish text with a CHECK vocabulary.
    scope          TEXT    NOT NULL DEFAULT 'custom'
        CHECK (scope IN ('ndev', 'nspec', 'ndoc', 'custom')),

    -- The tree's ROOT node (NULL while the tree has no nodes yet). SET NULL if that node is
    -- deleted (the workflow survives, rootless, until re-rooted).
    root_node_id   TEXT    REFERENCES nodes(id) ON DELETE SET NULL,

    -- Provenance: the workflow this one was forked from (NULL = not a fork). SET NULL if the
    -- source workflow is deleted — a fork outlives its origin.
    forked_from    TEXT    REFERENCES workflows(id) ON DELETE SET NULL,

    created_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The "which workflows does THIS project own" + "the built-in defaults" scans.
CREATE INDEX idx_workflows_project ON workflows (project_id);
CREATE INDEX idx_workflows_scope ON workflows (scope);

-- --- nodes: the PURE behavior tree (parent_id + order_index) -----------------

CREATE TABLE nodes (
    -- UUIDv7 generated by the backend.
    id             TEXT    NOT NULL PRIMARY KEY,

    -- The workflow this node belongs to. ON DELETE CASCADE: dropping a workflow drops all its
    -- nodes (a node has no meaning without its tree).
    workflow_id    TEXT    NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,

    -- The PARENT composite (NULL = the workflow's root node). Self-FK, ON DELETE CASCADE:
    -- deleting a composite deletes its whole subtree.
    parent_id      TEXT    REFERENCES nodes(id) ON DELETE CASCADE,

    -- Sibling ORDER under the parent (0-based). The child list of a composite is these rows,
    -- sorted by `order_index` — the ordering that makes the tree reconstructible.
    order_index    INTEGER NOT NULL DEFAULT 0,

    -- The node TYPE — the behavior-tree vocabulary. The FULL PRD model, forward-compatible:
    -- the 3 COMPOSITES (sequence/loop/selector) + the 8 LEAVES (spawn_subagent/judge/ask_human/
    -- produce/gate_check/transition/wait/note). `type` is a SQL/Rust keyword — double-quoted
    -- here and exposed to Rust as `type_` via `#[sql_name = "type"]` (like `tasks`).
    "type"         TEXT    NOT NULL
        CHECK ("type" IN (
            'sequence', 'loop', 'selector',
            'spawn_subagent', 'judge', 'ask_human', 'produce',
            'gate_check', 'transition', 'wait', 'note'
        )),

    -- Human label of this node instance (free text; the visualiser paints it).
    label          TEXT    NOT NULL DEFAULT '',

    -- The node's typed CONFIG, a JSON object whose shape depends on `type` (the interpreter
    -- decodes it per kind). Default '{}' = no config. Stored as TEXT (SQLite has no JSON type).
    config         TEXT    NOT NULL DEFAULT '{}',

    created_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at     INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The tree reads: "all nodes of a workflow" and "the ordered children of a composite".
CREATE INDEX idx_nodes_workflow ON nodes (workflow_id);
CREATE INDEX idx_nodes_parent ON nodes (parent_id, order_index);

-- --- workflow_runs: one live execution (cursor + blackboard) -----------------

CREATE TABLE workflow_runs (
    -- UUIDv7 generated by the backend.
    id               TEXT    NOT NULL PRIMARY KEY,

    -- The workflow being executed. ON DELETE CASCADE: dropping a workflow drops its runs.
    workflow_id      TEXT    NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,

    -- The Spec this run drives (NULL = a run not bound to a Spec). ON DELETE SET NULL: a run's
    -- history survives its Spec's deletion (the run happened), just loses the pointer.
    spec_id          TEXT    REFERENCES specs(id) ON DELETE SET NULL,

    -- The CURSOR: the node the run is currently parked on (NULL before the first tick / after
    -- completion). SET NULL if that node is deleted out from under a live run.
    current_node_id  TEXT    REFERENCES nodes(id) ON DELETE SET NULL,

    -- The run's BLACKBOARD: a JSON object scratchpad the interpreter reads/writes (last gate
    -- verdict, phase index, findings count, last diff, …). Default '{}' = empty board.
    blackboard       TEXT    NOT NULL DEFAULT '{}',

    -- The run lifecycle: running (live), blocked (a hard gate is red — cannot advance), done
    -- (reached the end), failed (aborted). CHECK-enforced.
    status           TEXT    NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'blocked', 'done', 'failed')),

    started_at       INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at       INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The "runs of a workflow" and "the run driving THIS Spec" scans.
CREATE INDEX idx_workflow_runs_workflow ON workflow_runs (workflow_id);
CREATE INDEX idx_workflow_runs_spec ON workflow_runs (spec_id);
