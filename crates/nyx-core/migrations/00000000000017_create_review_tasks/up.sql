-- Schema v17: the `review_tasks` and `review_reads` tables (v2.4 — Diff et review locale,
-- Phase 5, task 01KX0F6JEKCEV2JCTMEBMM3P4Z — "Promotion comment→task (finding=task) + non-lus
-- temps réel", PDR-0012/0015).
--
-- ## `finding = task` — the promoted comment IS the coder task (PDR-0012)
--
-- A review comment PROMOTED for the coder becomes a `review_tasks` row. There is deliberately
-- NO abstract `review_findings` vs `tasks` split and NO revival of the old
-- `review_findings`-as-annotation model: this table IS the coder task issued from the review
-- (the identifier honours phase-4's rationale — the promoted comment becomes a task row, not a
-- distinct "finding"). It links back to its source comment via `from_comment_id` (the proto's
-- `types.ts::Finding` traced: id / repositoryId / fromCommentId / title / severity? / status).
-- It anchors on the SAME `(workspace, repository)` correlation as the comment (plain values, no
-- FK CASCADE — a task must survive Git churn / a workspace archive like `review_comments` /
-- `domain_events`).
--
-- ## The "grill" flow (load-bearing, PDR-0012)
--
-- Promotion is a THREE-actor grill, modelled by `grill_state`:
--
--   proposed  → the HUMAN lâche brut: initiates the promotion from a comment, WITHOUT
--               structuring it. `title` seeds from the comment body; `details` is NULL.
--   structured→ the AGENT structures the task (a clean `title` + `details`), via an MCP tool.
--               The agent may structure but NEVER validate (the human-only guard-rail,
--               symmetric to phase-4 human-only comment resolution).
--   validated → the HUMAN validates the structured task. ONLY a `validated` task is "ready
--               for the coder" — the coder works on tasks (validated promotions), never on raw
--               comments.
--
-- The transitions are enforced by actor at the use-case + MCP façade layer (the agent tool set
-- carries a `structure` tool but NO `validate` tool). `grill_state` is CHECK-enforced to the
-- three states; a promotion is created `proposed`.
--
-- ## Severity OPTIONAL
--
-- `severity` is NULLABLE (info|low|medium|high|critical, CHECK-enforced when present) — a
-- promotion carries a severity only when the reviewer/agent chooses one.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the Rust
-- layer, with a portable julianday DEFAULT as a raw-insert safety net.

CREATE TABLE review_tasks (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it). This id is the
    -- coder-task id (finding = task): no separate human-facing key at this layer.
    id                TEXT    NOT NULL PRIMARY KEY,

    -- The (workspace, repository) the task — like its source comment — anchors on. Plain
    -- correlation columns (no FK CASCADE): a task is a derived-review artifact that must
    -- survive Git churn / a workspace archive the same way `review_comments` does.
    workspace_id      TEXT    NOT NULL,
    repository_id     TEXT    NOT NULL,

    -- The comment this task was PROMOTED from (finding = a promoted comment). A plain
    -- correlation value (no FK CASCADE): the task is durable coder work and outlives a
    -- delete/resolve of the source comment (the trail back to the annotation, not a lifecycle
    -- dependency).
    from_comment_id   TEXT    NOT NULL,

    -- The task title. Seeded from the comment body at promotion (proposed), rewritten clean by
    -- the agent at structuring.
    title             TEXT    NOT NULL,
    -- The structured task detail (NULL until the agent structures it).
    details           TEXT,

    -- OPTIONAL severity (info|low|medium|high|critical). NULL = no severity chosen.
    severity          TEXT    CHECK (severity IN ('info', 'low', 'medium', 'high', 'critical')),

    -- The grill lifecycle: proposed (human lâche brut) → structured (agent structures via MCP)
    -- → validated (human validates; only then is it ready for the coder). CHECK-enforced.
    grill_state       TEXT    NOT NULL DEFAULT 'proposed'
                              CHECK (grill_state IN ('proposed', 'structured', 'validated')),

    created_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The common read: "the tasks of this (workspace, repository)" (the review's promoted-task
-- list). Ordered scans key on created_at at the query layer.
CREATE INDEX idx_review_tasks_repo ON review_tasks (workspace_id, repository_id);

-- "the task(s) promoted from this comment" — the trail from a comment to its promotion.
CREATE INDEX idx_review_tasks_comment ON review_tasks (from_comment_id);

-- ## `review_reads` — the UNREAD watermark per (workspace, repository)
--
-- Reuses the runtime's `unread` PATTERN (terminals/command_instances carry a read/unread flag
-- the UI acknowledge clears). Here the review feed's unread count is derived from a per-repo
-- READ WATERMARK: `last_read_at` is the epoch-ms up to which the human has seen the comment
-- feed. The unread count = comments (roots + replies) whose `created_at` is STRICTLY AFTER
-- `last_read_at`. A new comment/reply (human OR agent via MCP) pushes the newest `created_at`
-- past the watermark → the count rises live; mark-read stamps `last_read_at = now` → back to 0.
-- ONE row per (workspace, repository); absent = never read (everything is unread).
CREATE TABLE review_reads (
    workspace_id      TEXT    NOT NULL,
    repository_id     TEXT    NOT NULL,
    -- Epoch-ms watermark: the human has seen every comment created at or before this instant.
    last_read_at      INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (workspace_id, repository_id)
);
