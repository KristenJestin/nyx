-- Schema v31: the PROTOTYPE domain — the prototype as the 1:1 ANNEXE of a Spec (v2.7 —
-- Prototype : machinerie, Phase 2, task 01KY4DFNPJHB2NNEH2CEG42GYE — "Persistance proto =
-- annexe 1:1 du Spec (porté de Depot)").
--
-- ## Why this domain (PDR-0009 — the prototype is an annexe of the Spec)
--
-- The prototype sub-system is RAPATRIATED from the legacy Depot system, ported to nyx-v2's
-- standards and to the frozen decisions of this PRD (PDR-0009). It models the iterative UI
-- design of a feature as a self-contained tree hung off ONE Spec:
--
--   Prototype → Page → PageVersion → Variant
--
-- plus whole-design ROUNDS (a manifest pinning which page version ships together — the
-- ROLLBACK unit) and pre-dev review COMMENTS anchored to a node of the component tree.
--
-- ## Ported from Depot, adapted to the frozen nyx decisions
--
--   * **1 proto per Spec** (Depot: N per prd_revision via a slug). The prototype hangs off a
--     `spec_id` with `UNIQUE(spec_id)` — the "annexe 1:1 du Spec" invariant. No slug.
--   * **Variant stores a COMPOSITION, not an HTML blob** (PDR-0010: "Proto stocké =
--     composition, pas blob HTML"). Depot's `html_content` becomes `composition_json` — the
--     serialized tree of named component nodes. The RENDER pipeline (a later phase) turns it
--     into markup; the persistence floor only holds it.
--   * **States are a variant axis, not a table** (Depot declares them in the variant HTML via
--     `window.__depotStates` — "ni une nouvelle table"). Ported as `states_json` on the
--     variant: the declared state NAMES (the shim's chip-bar reads them later). A logic-less
--     port that stays pure persistence.
--   * **Comments anchored to a TREE NODE, not a CSS selector** (PDR-0009: "ancrés à un NŒUD
--     DE L'ARBRE DE COMPOSANTS (pas un sélecteur CSS)"). `node_key` is the anchor; comments
--     are OWNED BY THE PROTOTYPE (not a single variant) so they are DURABLE CROSS-ROUNDS —
--     carried ("portés") while the node persists, flagged "à ré-ancrer" (`anchor_status =
--     orphaned`) when it does not, exactly like code-review anchors surviving churn. Comments
--     are a PRE-DEV review artifact: the AGENT corrects the design before election; they are
--     NEVER transmitted to the coder (it is the corrected composition that ships).
--   * **Two-tier election** (PDR-0009: "is_main(reco agent) ≠ RETENU(choix user)").
--     `prototype_variants.is_main` is the AGENT's within-version recommendation;
--     `prototype_round_pages.chosen_variant_id` (+ the decision record) is the USER's RETENU
--     choice, round-scoped (Depot's evolved model — a re-opened round no longer drags a stale
--     choice). Both reversible, distinct.
--   * **The separate distillation is DROPPED** (PDR-0010 reframe: "Pas de distillation
--     ré-écrite séparée : l'ARBRE EST LE CONTRAT"). Depot's `prd_round_page_design`
--     (placement_spec markdown) is NOT ported. The scope's "spec_design_lock" survives only as
--     a minimal FREEZE MARKER (`prototype_design_lock`) recording which round was frozen as THE
--     design ("Distill" se réduit à FIGER l'élection), with NO placement blob.
--
-- All election / cross-tree pointers (`chosen_variant_id`, `resolution_via_variant_id`,
-- `origin_variant_id`, `locked_round_id`, `node_key`) are stored as PLAIN ids (no FK), like
-- Depot and like `review_comments`'s correlation ids: they are soft references whose integrity
-- lives in the backend, and keeping them FK-free keeps the durable comment / election records
-- from being cascade-deleted out from under an audit. The HIERARCHY edges (parent → child) are
-- real FKs with ON DELETE CASCADE.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the Rust
-- backend on every write, with the portable julianday DEFAULT as a raw-insert safety net.

-- --- prototypes: the per-Spec prototype (annexe 1:1) --------------------------

CREATE TABLE prototypes (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id           TEXT    NOT NULL PRIMARY KEY,

    -- The Spec this prototype is the annexe of (PDR-0009). ON DELETE CASCADE: the prototype
    -- has no meaning without its Spec (like `annexes`).
    spec_id      TEXT    NOT NULL REFERENCES specs(id) ON DELETE CASCADE,

    -- Free-form description of what the prototype covers (nullable).
    description  TEXT,

    created_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- Archived (soft-removed) prototype, kept for audit/rollback. NULL = live.
    archived_at  INTEGER
);

-- "1 proto/Spec" (PDR-0009): a Spec has AT MOST one prototype. The backend `create_prototype`
-- keys on this to reject a second one.
CREATE UNIQUE INDEX idx_prototypes_spec ON prototypes (spec_id);

-- --- prototype_pages: a logical screen (a route) -----------------------------

CREATE TABLE prototype_pages (
    id            TEXT    NOT NULL PRIMARY KEY,

    -- The prototype the page belongs to. ON DELETE CASCADE.
    prototype_id  TEXT    NOT NULL REFERENCES prototypes(id) ON DELETE CASCADE,

    -- Stable slug: the `data-nyx-page="<slug>"` navigation convention resolves through it, so
    -- it survives a title rename. UNIQUE per prototype (index below).
    slug          TEXT    NOT NULL,
    title         TEXT    NOT NULL,
    position      INTEGER NOT NULL DEFAULT 0,

    created_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

CREATE INDEX idx_prototype_pages_prototype ON prototype_pages (prototype_id);
CREATE UNIQUE INDEX idx_prototype_pages_prototype_slug ON prototype_pages (prototype_id, slug);

-- --- prototype_page_versions: a page ITERATION (frozen; older stays readable) ---

CREATE TABLE prototype_page_versions (
    id           TEXT    NOT NULL PRIMARY KEY,

    -- The page this is a version of. ON DELETE CASCADE.
    page_id      TEXT    NOT NULL REFERENCES prototype_pages(id) ON DELETE CASCADE,

    label        TEXT    NOT NULL,
    summary      TEXT,

    created_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- A version is FROZEN once minted; the agent iterates by minting a NEW version. Archiving
    -- keeps the older version READABLE for audit / ROLLBACK (never mutated). NULL = live.
    archived_at  INTEGER
);

CREATE INDEX idx_prototype_page_versions_page ON prototype_page_versions (page_id);
CREATE UNIQUE INDEX idx_prototype_page_versions_page_label ON prototype_page_versions (page_id, label);

-- --- prototype_variants: one concrete rendering of a (page, version) ----------

CREATE TABLE prototype_variants (
    id               TEXT    NOT NULL PRIMARY KEY,

    -- The page version this variant renders. ON DELETE CASCADE.
    page_version_id  TEXT    NOT NULL REFERENCES prototype_page_versions(id) ON DELETE CASCADE,

    label            TEXT    NOT NULL,
    title            TEXT    NOT NULL,

    -- The COMPOSITION: the serialized tree of named component nodes (PDR-0010 — "Proto stocké =
    -- composition, pas blob HTML"). Default '' so a freshly-minted variant is a valid row before
    -- the agent fills the tree. The render pipeline (a later phase) turns it into markup.
    composition_json TEXT    NOT NULL DEFAULT '',

    -- The DECLARED states of this variant (JSON array of state names — the `window.__depotStates`
    -- port). NULL when the variant declares none (no chip-bar). "État = param" (PDR-0010); the
    -- shim reads these later.
    states_json      TEXT,

    -- The AGENT's within-version recommendation (PDR-0009: `is_main` = reco de l'agent). Distinct
    -- from the USER's RETENU (round_pages.chosen_variant_id). At most one main per page version is
    -- an invariant kept by the backend (`set_main_variant`), not SQL.
    is_main          INTEGER NOT NULL DEFAULT 0,
    position         INTEGER NOT NULL DEFAULT 0,

    created_at       INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

CREATE INDEX idx_prototype_variants_page_version ON prototype_variants (page_version_id);
CREATE UNIQUE INDEX idx_prototype_variants_page_version_label ON prototype_variants (page_version_id, label);

-- --- prototype_feedback: pre-dev review comments, anchored to a TREE NODE ------

CREATE TABLE prototype_feedback (
    id                       TEXT    NOT NULL PRIMARY KEY,

    -- OWNED BY THE PROTOTYPE (not a single variant) so a comment is DURABLE CROSS-ROUNDS
    -- (PDR-0009). ON DELETE CASCADE: a removed prototype drops its comments.
    prototype_id             TEXT    NOT NULL REFERENCES prototypes(id) ON DELETE CASCADE,

    -- WHERE the comment was raised (the variant on screen at pin time). A PLAIN id (no FK): the
    -- comment OUTLIVES that variant being pruned (durability), and the anchor of record is
    -- `node_key`, not this variant. NULL for a free-form / global comment.
    origin_variant_id        TEXT,

    -- THE ANCHOR: a stable key identifying a NODE of the component tree (PDR-0009 — "ancrés à un
    -- NŒUD DE L'ARBRE DE COMPOSANTS (pas un sélecteur CSS)"). NULL for a global comment.
    node_key                 TEXT,

    -- Durability across rounds: 'anchored' = the node still exists → the comment is CARRIED
    -- ("porté") ; 'orphaned' = the node vanished → the comment is "à ré-ancrer" (surfaced for
    -- re-anchoring, code-review style). The backend flips this when reconciling a new round.
    anchor_status            TEXT    NOT NULL DEFAULT 'anchored',

    -- The comment text (the review note).
    body                     TEXT    NOT NULL,

    -- 'open' | 'resolved' | 'ignored'. Resolution is an explicit annotation for the audit log
    -- (PDR-0009 — the agent corrects the design, then the comment is resolved).
    status                   TEXT    NOT NULL DEFAULT 'open',
    resolution_note          TEXT,
    -- The variant that ADDRESSED the comment (a PLAIN id, no FK — same durability rationale).
    resolution_via_variant_id TEXT,
    resolved_at              INTEGER,
    ignored_reason           TEXT,
    ignored_at               INTEGER,

    -- WHO authored it, resolved at execution (PDR-0009: "auteur = session/utilisateur"):
    -- 'session' (an agent session) | 'user'. `author_ref` carries the session id / user handle.
    author_kind              TEXT    NOT NULL DEFAULT 'user',
    author_ref               TEXT,

    created_at               INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at               INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

CREATE INDEX idx_prototype_feedback_prototype ON prototype_feedback (prototype_id);
CREATE INDEX idx_prototype_feedback_prototype_status ON prototype_feedback (prototype_id, status);

-- --- prototype_rounds: a whole-design round (the ROLLBACK unit) ---------------

CREATE TABLE prototype_rounds (
    id            TEXT    NOT NULL PRIMARY KEY,

    -- The prototype the round belongs to. ON DELETE CASCADE.
    prototype_id  TEXT    NOT NULL REFERENCES prototypes(id) ON DELETE CASCADE,

    label         TEXT    NOT NULL,
    summary       TEXT,

    -- The CURRENT round is the one with the maximum `position` (the only mutable one); earlier
    -- rounds are frozen by construction — the ROLLBACK targets (PDR-0009: rounds gardés comme
    -- rollback).
    position      INTEGER NOT NULL DEFAULT 0,

    -- When set, the round was PRESENTED to the user (a handback). A presented round is FROZEN:
    -- feedback opens a NEW round, never mutates the presented one (PDR-0009: feedback ⇒ nouveau
    -- round). NULL = still in construction.
    presented_at  INTEGER,

    created_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

CREATE INDEX idx_prototype_rounds_prototype ON prototype_rounds (prototype_id);
CREATE UNIQUE INDEX idx_prototype_rounds_prototype_label ON prototype_rounds (prototype_id, label);

-- --- prototype_round_pages: a round's manifest + the round-scoped RETENU -------

CREATE TABLE prototype_round_pages (
    id               TEXT    NOT NULL PRIMARY KEY,

    -- The round this manifest row belongs to. ON DELETE CASCADE.
    round_id         TEXT    NOT NULL REFERENCES prototype_rounds(id) ON DELETE CASCADE,

    -- The page pinned into the round, and WHICH version of it ships. Both ON DELETE CASCADE.
    page_id          TEXT    NOT NULL REFERENCES prototype_pages(id) ON DELETE CASCADE,
    page_version_id  TEXT    NOT NULL REFERENCES prototype_page_versions(id) ON DELETE CASCADE,
    position         INTEGER NOT NULL DEFAULT 0,

    -- The USER's RETENU (PDR-0009: RETENU = choix de l'utilisateur), round-scoped: the variant
    -- elected for THIS page IN THIS round + the arbitration record (rationale / who / when). A
    -- PLAIN id (no FK) — integrity in the backend (`elect_round_page_variant`). NULL = no EXPLICIT
    -- election yet — but the EFFECTIVE RETENU still resolves "d'office" to the lone variant of a
    -- mono-variant page (PDR-0009: nothing to arbitrate), via `db::effective_retained_variant`.
    chosen_variant_id   TEXT,
    decision_rationale  TEXT,
    decided_by          TEXT,
    decided_at          INTEGER,

    created_at       INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

CREATE INDEX idx_prototype_round_pages_round ON prototype_round_pages (round_id);
CREATE INDEX idx_prototype_round_pages_page ON prototype_round_pages (page_id);
CREATE UNIQUE INDEX idx_prototype_round_pages_round_page ON prototype_round_pages (round_id, page_id);

-- --- prototype_design_lock: the FREEZE marker ("figer l'élection") ------------
--
-- The reframed "distill" (PDR-0010): freezing the elected round as THE design for the Spec.
-- ONE row per prototype (a re-lock updates it in place). NO placement blob — the composition
-- tree IS the contract, so there is nothing to re-write. `locked_round_id` is a PLAIN id
-- (integrity in the backend). This is the ONLY survivor of Depot's `prd_design_lock` /
-- `prd_round_page_design`; the placement_spec markdown they carried is deliberately DROPPED.

CREATE TABLE prototype_design_lock (
    prototype_id     TEXT    NOT NULL PRIMARY KEY REFERENCES prototypes(id) ON DELETE CASCADE,
    locked_round_id  TEXT    NOT NULL,
    decided_by       TEXT,
    locked_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);
