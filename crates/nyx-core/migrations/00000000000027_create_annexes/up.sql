-- Schema v27: ANNEXES attached to a Spec — a content-addressed `annex_blobs` store + the
-- `annexes` attachment rows (v2.6 — Idées entretenues, annexes & dépendances Spec, Phase 3,
-- task 01KXZ9K43C9ZMQ3M5JR07M78HV — "Annexes attachées à une Spec (stockage interne + dédup
-- content_hash) + MCP").
--
-- ## Why two tables (PRD Impl Decisions "ANNEXES")
--
-- An annexe attaches a doc / artefact / URL / prototype to a Spec, with INTERNAL storage (no
-- fragile link to a repo file that will move/rename) and DEDUP by content_hash ("le même
-- artefact attaché deux fois = une seule copie"). The clean way to guarantee "one physical
-- copy" is a CONTENT-ADDRESSED blob store:
--
--   * `annex_blobs` — the internal store, keyed by `content_hash` (SHA-1 hex of the content,
--     computed by the Rust backend). ONE row per distinct content, GLOBAL across the whole DB
--     (the dedup scope): attaching the same bytes twice — to the same Spec or to another — is
--     an `INSERT OR IGNORE` on this table, so the content is stored EXACTLY ONCE.
--   * `annexes` — the lightweight ATTACHMENT rows: each points at its Spec (`spec_id`) and at
--     a blob (`content_hash`), carrying the display `kind` + `title`. N attachments can share
--     one blob; removing the last attachment of a blob GC-drops the blob (backend, in the same
--     transaction) so the store never accretes orphans (the PRD "entretien" ethos).
--
-- `kind` is the display/type facet (doc / artefact / url / prototype); for a `url` the "content"
-- IS the URL string (an internal pointer, still content-addressed & deduped). Timestamps mirror
-- the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the Rust backend on write,
-- with the portable julianday DEFAULT as a raw-insert safety net.

-- --- annex_blobs: the content-addressed internal store (global dedup) ---------

CREATE TABLE annex_blobs (
    -- The content HASH (SHA-1 hex, 40 chars), computed by the backend over `content`. PRIMARY
    -- KEY = the dedup axis: the same content maps to the same row, stored once (content-
    -- addressed). GLOBAL scope (not per-Spec) so an artefact shared across Specs is one copy.
    content_hash TEXT    NOT NULL PRIMARY KEY,

    -- The stored copy of the annexe's content (the doc/artefact text, or the URL string for a
    -- `url` annexe). INTERNAL — never a path into a repo that could move.
    content      TEXT    NOT NULL,

    -- The content's byte length, surfaced by the list/get reads (a size hint without shipping
    -- the whole body in a list).
    byte_len     INTEGER NOT NULL,

    created_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- --- annexes: the per-Spec attachment rows -----------------------------------

CREATE TABLE annexes (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id           TEXT    NOT NULL PRIMARY KEY,

    -- The Spec this annexe is attached to. ON DELETE CASCADE: deleting a Spec removes its
    -- annexe attachment rows (their blobs are GC'd by the backend on the last-reference drop).
    spec_id      TEXT    NOT NULL REFERENCES specs(id) ON DELETE CASCADE,

    -- The display/type facet of the annexe. CHECK-enforced vocabulary.
    kind         TEXT    NOT NULL
        CHECK (kind IN ('doc', 'artefact', 'url', 'prototype')),

    -- Human-facing title of the attachment.
    title        TEXT    NOT NULL,

    -- Pointer into the content-addressed store: which blob holds this annexe's bytes. RESTRICT
    -- (the default FK action) — a blob is only ever removed by the backend once its LAST
    -- referencing annexe is gone, so this FK is never dangling.
    content_hash TEXT    NOT NULL REFERENCES annex_blobs(content_hash),

    created_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- The list read is per Spec, newest-first — index the scan key.
CREATE INDEX idx_annexes_spec ON annexes (spec_id);

-- Reverse-lookup index for the blob GC ("does any annexe still reference THIS content_hash?").
CREATE INDEX idx_annexes_content_hash ON annexes (content_hash);
