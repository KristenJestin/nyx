-- Schema v14: the task domain — `tasks` + `task_dependencies` (v2.4 Phase 2, task
-- 01KX1DH5TVVA2QJFKMXSWSR4DD — "Modèle task (slice/human/review) + dépendances +
-- findings"). The delegable unit of work of a Spec — what the coder actually picks up
-- (PDR-0014). Builds on the Phase 1 Spec domain (v13): a task links to a Spec.
--
-- ## Why these tables (canonical model + PRD Impl Decisions)
--
-- A `task` is the atom the coder works on. The PRD names THREE kinds — `slice` (a chunk
-- of agent implementation work), `human` (an action only the user can do — secret
-- rotation, manual validation…, surfaced in the Attention Inbox, VERIFIABLE), and
-- `review` (a finding: FINDING = TASK, there is NO separate findings table — a review
-- finding is just a task carrying a `severity`). Those three PRD kinds fold onto the
-- canonical `tasks` columns from `docs/product/data-model.dbml` (lines 325-352):
--   * `kind` (this migration's addition) carries the PRD's slice|human|review vocabulary
--     verbatim, the single word the authoring UI/MCP speaks.
--   * `executor` (canonical `task_executor` agent|human) is DERIVED-consistent: a `human`
--     task has `executor='human'`, `slice`/`review` have `executor='agent'`. A CHECK
--     keeps them coherent so the two can never contradict (a `human` kind that is not
--     executor=human, or vice-versa, is rejected).
--   * `severity` (canonical `severity`, nullable) makes a `review` task a FINDING (the
--     finding=task decision, PDR-0016). NULL on a non-finding.
--   * `type` (canonical `task_type`) + `status` (canonical `task_status`) + `priority`
--     (canonical `priority`) + `phase` (indexes `specs.phases`, PDR-0022) + `position`
--     round out the canonical shape.
--
-- The DEPENDENCY graph is a separate edge table `task_dependencies` (canonical, lines
-- 354-363): a directed edge `task_id --depends_on--> depends_on_task_id`. The graph MUST
-- stay ACYCLIC — a new edge that would create a cycle is refused in the backend
-- (`db.rs::add_task_dependency` runs a DFS reachability check before inserting). SQLite
-- has no cheap in-SQL cycle check, so the acyclicity invariant is enforced in Rust, the
-- single writer through which every edge is added.
--
-- HUMAN-ACTION VERIFIABILITY: a `kind=human` task carries a `verification_command`
-- (nullable free text — how the human action is confirmed, e.g. a check to run or a
-- description of the evidence). The backend's guarded `verify_human_task` path marks a
-- human task done ONLY once it is verifiable/verified, so a human action cannot be
-- silently closed without its verification being recorded (mirrors depot's `task verify`).
--
-- Follows `docs/product/data-model.dbml` (the canonical `tasks` / `task_dependencies`
-- shape) and PDR-0024 (ONE SQLite file, one migration chain) — this is just the next link
-- after v13.
--
-- ## Scope (this task = the MODEL only)
--
--   * NO review capability (v2.5) — a `review`/finding task is only the MODEL here; the
--     review that PRODUCES findings is out of phase.
--   * NO UI (the tasks tab is a separate later task) and NO MCP tools.
--   * `parent_task_id` (canonical, lines 330) — a task can be a subtask of another — is
--     included (nullable, self-FK) so the acyclic decomposition tree is representable
--     alongside the dependency graph.
--   * The author-provenance columns `created_by_type` / `created_by_id` (canonical
--     NOT-NULL per `docs/product/data-model.dbml` lines 340-341) are DEFERRED, exactly as
--     Phase 1 deferred them on `specs`/`spec_revisions`: there is no "who" to record until
--     the MCP authoring layer (v2.4 Phase 5) exists to supply it. Adding them NOT-NULL now
--     is impossible (no author to write) and a nullable placeholder would diverge from the
--     canonical shape, so they are recorded here as a deliberate scoping choice, NOT added.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, set explicitly
-- by the Rust backend on every write, with the portable julianday DEFAULT as a safety net.

-- --- tasks: the delegable unit of work -----------------------------------------

CREATE TABLE tasks (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it). PDR-0014:
    -- decomposition is agent-managed, so there is NO human key (ULID) — the id is opaque.
    id            TEXT    NOT NULL PRIMARY KEY,

    -- The project the task belongs to. ON DELETE CASCADE: removing a project removes its
    -- tasks (a task has no meaning without its project).
    project_id    TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The Spec the task belongs to (the delegable unit of a Spec). NULLABLE: a task can
    -- exist without a Spec (light work), per the canonical Note. ON DELETE CASCADE: a task
    -- is a child of its Spec, removed with it.
    spec_id       TEXT    REFERENCES specs(id) ON DELETE CASCADE,

    -- Optional parent task (subtask decomposition tree). Self-FK, nullable. ON DELETE
    -- CASCADE: removing a parent removes its subtasks.
    parent_task_id TEXT   REFERENCES tasks(id) ON DELETE CASCADE,

    -- The PRD KIND: slice (agent work chunk) / human (user-only action) / review (a
    -- finding). The single word the authoring layer speaks; folds onto executor/severity
    -- below. Default 'slice'.
    kind          TEXT    NOT NULL DEFAULT 'slice'
        CHECK (kind IN ('slice', 'human', 'review')),

    -- Canonical `task_executor`: who runs it (agent|human). KEPT COHERENT with `kind`:
    -- a `human` kind must be executor='human'; a `slice`/`review` kind must be
    -- executor='agent'. Default 'agent'.
    executor      TEXT    NOT NULL DEFAULT 'agent'
        CHECK (executor IN ('agent', 'human')),

    -- Canonical `task_type` (implementation|investigation|validation|documentation|
    -- migration). Default 'implementation'.
    type          TEXT    NOT NULL DEFAULT 'implementation'
        CHECK (type IN ('implementation', 'investigation', 'validation',
                        'documentation', 'migration')),

    -- Lifecycle status (canonical `task_status`). The GUARDED transitions
    -- (start/done/block/skip) are carried in the backend (db.rs); this column stores it
    -- with the `todo` default. `cancelled` is the skip target.
    status        TEXT    NOT NULL DEFAULT 'todo'
        CHECK (status IN ('todo', 'ready', 'in_progress', 'blocked',
                          'in_review', 'done', 'cancelled')),

    -- Stored priority (canonical `priority`). Default 'med'.
    priority      TEXT    NOT NULL DEFAULT 'med'
        CHECK (priority IN ('urgent', 'high', 'med', 'low')),

    -- FINDING severity (canonical `severity`, nullable): set makes the task a review
    -- FINDING (finding=task, PDR-0016). NULL on a non-finding. CHECK the vocabulary when
    -- present.
    severity      TEXT
        CHECK (severity IS NULL OR severity IN ('info', 'low', 'medium', 'high', 'critical')),

    -- Human-facing title, and optional long-form body + acceptance criteria.
    title         TEXT    NOT NULL,
    description   TEXT,
    acceptance_criteria TEXT,

    -- HUMAN-ACTION VERIFIABILITY: how a `kind=human` task is confirmed (a check to run or
    -- the evidence to look for). Nullable; the guarded verify path requires it before a
    -- human task can be marked done. NULL on a non-human task.
    verification_command TEXT,

    -- Phase grouping: indexes `specs.phases` (PDR-0022). Nullable = no phase (tasks flat).
    phase         INTEGER,

    -- List/board position within the Spec. Default 0.
    position      INTEGER NOT NULL DEFAULT 0,

    -- Free-text reason recorded when the task is blocked or skipped (the transition path
    -- stamps it; NULL otherwise).
    blocked_reason TEXT,
    skip_reason   TEXT,

    created_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- Epoch ms the task reached `done`. NULL while not done.
    completed_at  INTEGER,

    -- A human kind is executor=human, and a non-human kind is executor=agent — the two
    -- vocabularies can never contradict (a `human` task that agents run, or a `slice`
    -- assigned to a human, is a data error).
    CHECK ((kind = 'human') = (executor = 'human'))
);

-- Board/list scans within a Spec are ordered by position.
CREATE INDEX idx_tasks_spec_position ON tasks (spec_id, position);

-- Board/kanban column scans within a project key on (project, status).
CREATE INDEX idx_tasks_project_status ON tasks (project_id, status);

-- Subtask lookups by parent.
CREATE INDEX idx_tasks_parent ON tasks (parent_task_id);

-- --- task_dependencies: the acyclic dependency graph ---------------------------

CREATE TABLE task_dependencies (
    -- The dependent task (the edge's HEAD): `task_id` depends on `depends_on_task_id`.
    task_id           TEXT    NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,

    -- The prerequisite task (the edge's TAIL): must be done before `task_id` can proceed.
    depends_on_task_id TEXT   NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,

    -- Canonical `dependency_type` (blocks|relates_to). Default 'blocks' (the ordering
    -- edge; 'relates_to' is a soft link that does not gate).
    type              TEXT    NOT NULL DEFAULT 'blocks'
        CHECK (type IN ('blocks', 'relates_to')),

    created_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- The (task, depends_on) pair is the PRIMARY KEY (canonical composite key): an edge is
    -- unique; a duplicate edge is a no-op the backend detects.
    PRIMARY KEY (task_id, depends_on_task_id),

    -- A task cannot depend on itself (the smallest cycle). Longer cycles are refused in the
    -- backend (`add_task_dependency` runs a reachability DFS before inserting), since
    -- SQLite cannot check transitive acyclicity in a CHECK.
    CHECK (task_id <> depends_on_task_id)
);

-- Reverse-lookup index: "what depends on this task" (the dependents of a prerequisite),
-- used by the cycle check's reachability walk and by dependent scans. The forward
-- direction is served by the composite PRIMARY KEY.
CREATE INDEX idx_task_dependencies_depends_on ON task_dependencies (depends_on_task_id);
