-- Schema v30: the DESIGN-SYSTEM domain — `design` (1 per project) + `design_components`
-- (1 per component) (v2.7 — Prototype : machinerie, Phase 1, task
-- 01KY4DFM5BS3JVSEZYJZVEFBF6 — "Tables design + components (schema nyx-core)").
--
-- ## Why this domain (the FIDÈLE distill, PRD Impl Decisions — PDR-0010)
--
-- The proto→dev distill is BROKEN: the human validates a prototype (layout, actions,
-- rendu) and the coder ships something VERY different, because the coder never receives
-- (or receives badly) the design-system + the mapped components that would guarantee a
-- rendu faithful to the app's standards. v2.7 rapatriates the design-system NATIVELY as
-- the single authority so the later context seam (PRD HARNAIS) can weave it into the
-- coder's context. This migration lays the persistence floor the inventory (task 2) and
-- the md5 sync (task 3) build on:
--
--   * `design` — ONE row per project: the DESIGN.md markdown (couleurs / typo / spacing /
--     elevation / guidelines) plus the derived `theme_tokens_json` used to build the
--     Tailwind config injected into the render iframe. Source of truth = nyx, exportable
--     as DESIGN.md. The `UNIQUE(project_id)` enforces the "1 per project" invariant.
--   * `design_components` — ONE row per component of the imposed library: `name`, the
--     `source_repository_id` (+ `source_path`) provenance, the `visual_hash` (the md5 of
--     the component's VISUAL part — template + styles, NOT the .ts logic — recomputed by
--     the task-3 incremental sync), the Handlebars `template` compiled in the sidecar, and
--     the `params_json` / `states_json` shapes. `source_*` NULL = a component born in
--     GREENFIELD (no front yet — the agent creates the lib later, task 2). The
--     `UNIQUE(project_id, name)` makes the inventory upsert idempotent (re-scanning never
--     duplicates a component).
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, stamped by the
-- Rust backend on every write, with the portable julianday DEFAULT as a raw-insert safety net.

-- --- design: the per-project design-system (DESIGN.md) -----------------------

CREATE TABLE design (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id                TEXT    NOT NULL PRIMARY KEY,

    -- The project this design-system belongs to. ON DELETE CASCADE: removing a project
    -- removes its design-system (it has no meaning without its project), like `ideas`.
    project_id        TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The DESIGN.md markdown (couleurs / typo / spacing / elevation / guidelines). Free-form
    -- markdown; default '' so a project can hold a design-system row before it is authored.
    content           TEXT    NOT NULL DEFAULT '',

    -- The derived theme tokens (JSON, nullable) used to build the Tailwind config injected
    -- into the render iframe. NULL until derived from `content`.
    theme_tokens_json TEXT,

    created_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at        INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- "1 per project" (PDR-0010): a project has AT MOST one design-system row. The backend
-- `upsert_design` keys on this to insert-or-update in place.
CREATE UNIQUE INDEX idx_design_project ON design (project_id);

-- --- design_components: the imposed component library --------------------------

CREATE TABLE design_components (
    -- UUIDv7 generated by the backend.
    id                   TEXT    NOT NULL PRIMARY KEY,

    -- The project the component belongs to. ON DELETE CASCADE like `design`.
    project_id           TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The component's name (e.g. `Button`), UNIQUE per project (index below). The inventory
    -- (task 2) derives it from the source file stem; it is the catalogue's human key.
    name                 TEXT    NOT NULL,

    -- Provenance: the repo + relative path the component was inventoried from. Both NULLABLE
    -- so a GREENFIELD component (born before any front exists — the agent creates the lib
    -- later) carries no source. ON DELETE SET NULL: archiving/removing the source repo leaves
    -- the component (its identity survives), just unlinked from a repo that no longer exists.
    source_repository_id TEXT    REFERENCES repositories(id) ON DELETE SET NULL,
    source_path          TEXT,

    -- The md5 of the component's VISUAL part (template + styles, NOT the .ts logic), for the
    -- INCREMENTAL sync (task 3): a visual change flips this hash → the component is reinjected;
    -- a logic-only (.ts) change leaves it untouched → no reinjection. NULL until first hashed.
    visual_hash          TEXT,

    -- The Handlebars (logic-less) template compiled in the sidecar to markup. Default '' so an
    -- inventoried-but-not-yet-templated component (or a greenfield stub) is a valid row; the
    -- render pipeline (later phase) fills it.
    template             TEXT    NOT NULL DEFAULT '',

    -- The component's editable params + its declared states (JSON, nullable). `states_json`
    -- models the declarative states (the shim's chip-bar); a state is itself a param.
    params_json          TEXT,
    states_json          TEXT,

    created_at           INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at           INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- "1 per component" (PDR-0010): a component name is UNIQUE within its project. The inventory
-- upsert (task 2) keys on this so a re-scan reconciles in place instead of duplicating.
CREATE UNIQUE INDEX idx_design_components_project_name ON design_components (project_id, name);
