-- Schema v13: the Spec domain — `specs` + `spec_revisions` (v2.4 Phase 1, task
-- 01KX1DH4QC04C1FKHZT5ZF4BMS — "Modèle Spec + révisions (nyx-core)"). The durable
-- unit of human work (PDR-0014) absorbed into nyx native, the foundation the rest of
-- the Spec domain (tasks, lifecycle, contexts) builds on.
--
-- ## Why these tables (canonical model + PRD Impl Decisions)
--
-- A Spec is a STORED entity (contrary to the review, which is a DERIVED view). It
-- carries a durable identity within its project (human key = `projects.key || '-' ||
-- specs.number`) and a chain of REVISIONS. A FORK creates a NEW revision and the
-- previous one becomes `superseded`; `specs.current_revision_number` points at the
-- single ACTIVE revision. The revision body is STRUCTURED into the six sections the
-- PRD names (problem / solution / implementationDecisions / testingDecisions /
-- userStories / outOfScope) rather than one opaque markdown blob — the authoring UI /
-- MCP tools (later phases) edit these sections directly, and `user_stories` /
-- `out_of_scope` live INSIDE the Spec revision (absorption.md: those Depot tables are
-- folded into the Spec, PDR-0016).
--
-- Follows `docs/product/data-model.dbml` (the canonical Spec shape) for the identity
-- columns, uniqueness, and the `spec_status` / `spec_mode` vocabularies, and PDR-0024
-- (ONE SQLite file, one migration chain) — this is just the next link.
--
-- ## Scope (this task = the MODEL only)
--
--   * NO lifecycle transitions / guards here (the NEXT task owns them — this migration
--     only stores `status` with its CHECK vocabulary and the `draft` default).
--   * NO tasks, NO UI, NO MCP.
--   * `workspace_id` is the seam RESERVED in v2.1 (a Spec is anchored on a dev
--     workspace; repos + project are DERIVED from the workspace). It is nullable and
--     realized (populated) by v2.4 Phase 3 — declared here so the FK exists, left NULL
--     for now. `milestone_id` / `category_id` are DEFERRED (their tables land later:
--     milestones v2.7, categories a later v2.4 task), so they are NOT columns yet.
--   * The author-provenance columns `created_by_type` / `created_by_id` (canonical
--     NOT-NULL on both tables per `docs/product/data-model.dbml`: specs lines 290-291,
--     spec_revisions lines 314-315) are DEFERRED too, and NOT columns yet. There is no
--     "who" to record until the MCP authoring layer exists to supply it — that layer,
--     and thus the population of these columns, lands in v2.4 Phase 5 ("Outils MCP
--     d'authoring + transitions"). Adding them now as NOT-NULL is impossible (no
--     author to write) and a nullable placeholder would diverge from the canonical
--     shape, so they are recorded here as a deliberate scoping choice rather than added.
--
-- Timestamps mirror the rest of the schema: epoch MILLISECONDS as INTEGER, set
-- explicitly by the Rust backend on every write, with the portable julianday DEFAULT
-- as a safety net for any raw insert.

-- --- specs: the durable Spec identity -----------------------------------------

CREATE TABLE specs (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id            TEXT    NOT NULL PRIMARY KEY,

    -- The project the Spec belongs to. ON DELETE CASCADE: removing a project removes
    -- its Specs (a Spec has no meaning without its project).
    project_id    TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The dev workspace the Spec is anchored on (specs.workspace_id — the v2.1
    -- reserved seam). The REPOS + the PROJECT of a review are DERIVED from this
    -- workspace. Nullable (posed at dev launch, overwritable, never lost). ON DELETE
    -- SET NULL: removing the workspace detaches the pointer rather than deleting the
    -- Spec. POPULATED by v2.4 Phase 3; NULL here.
    workspace_id  TEXT    REFERENCES workspaces(id) ON DELETE SET NULL,

    -- Human-facing title, and an optional descriptive slug kept for the URL.
    title         TEXT    NOT NULL,
    slug          TEXT,

    -- Per-project sequence number: the human key is `projects.key || '-' || number`
    -- (e.g. NYX-42). UNIQUE within the project (see the index below).
    number        INTEGER NOT NULL,

    -- Stored priority (string vocabulary, canonical `priority` enum). Default 'med'.
    priority      TEXT    NOT NULL DEFAULT 'med'
        CHECK (priority IN ('urgent', 'high', 'med', 'low')),

    -- Lifecycle status (canonical `spec_status` vocabulary). This migration stores it
    -- with the `draft` default; the GUARDED/VALIDATED transitions are the NEXT task.
    status        TEXT    NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'ready', 'in_progress', 'blocked',
                          'in_review', 'completed', 'cancelled', 'archived')),

    -- Authoring mode (canonical `spec_mode`): stepped (human validates each step) or
    -- autopilot. Default 'stepped'.
    mode          TEXT    NOT NULL DEFAULT 'stepped'
        CHECK (mode IN ('stepped', 'autopilot')),

    -- Ordered phase plan as a JSON list `[{number,name}]` (PDR-0022): tasks.phase
    -- indexes this list; phase status is DERIVED from tasks, there is no phases table.
    -- Default '[]' (no phases = tasks flat). The pre-ready validation (next task)
    -- checks its coherence.
    phases        TEXT    NOT NULL DEFAULT '[]',

    -- Points at the single ACTIVE revision (a FORK bumps this to the new revision).
    current_revision_number INTEGER NOT NULL DEFAULT 1,

    -- Board/list position within the project. Default 0.
    position      INTEGER NOT NULL DEFAULT 0,

    created_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),

    -- Terminal-state timestamps (epoch ms), NULL while the Spec is active.
    completed_at  INTEGER,
    archived_at   INTEGER
);

-- The per-project sequence number is UNIQUE (the human key axis).
CREATE UNIQUE INDEX idx_specs_project_number ON specs (project_id, number);

-- The descriptive slug is UNIQUE within a project WHEN present (a Spec may have no
-- slug; only the ones that do participate — a partial unique index).
CREATE UNIQUE INDEX idx_specs_project_slug ON specs (project_id, slug)
    WHERE slug IS NOT NULL;

-- Index the (project, status) pair for the board/kanban column scans.
CREATE INDEX idx_specs_project_status ON specs (project_id, status);

-- --- spec_revisions: the revision chain (FORK = new revision) -----------------

CREATE TABLE spec_revisions (
    -- UUIDv7 generated by the backend.
    id            TEXT    NOT NULL PRIMARY KEY,

    -- The Spec this revision belongs to. ON DELETE CASCADE with the Spec.
    spec_id       TEXT    NOT NULL REFERENCES specs(id) ON DELETE CASCADE,

    -- Monotonic revision number within the Spec (1, 2, 3…). UNIQUE per Spec.
    revision_number INTEGER NOT NULL,

    -- Revision lifecycle: `active` (the current, editable revision) or `superseded`
    -- (a FORK created a newer revision, retiring this one). Exactly ONE `active`
    -- revision per Spec (a partial unique index enforces it) — the one
    -- `specs.current_revision_number` points at.
    revision_status TEXT  NOT NULL DEFAULT 'active'
        CHECK (revision_status IN ('active', 'superseded')),

    -- Revision title (snapshot of the Spec title at revision time).
    title         TEXT    NOT NULL,

    -- The STRUCTURED sections (PRD Impl Decisions). Each is markdown text, default ''
    -- (a fresh draft has empty sections). `user_stories` / `out_of_scope` live here,
    -- inside the Spec revision (absorption.md, PDR-0016).
    problem                 TEXT NOT NULL DEFAULT '',
    solution                TEXT NOT NULL DEFAULT '',
    implementation_decisions TEXT NOT NULL DEFAULT '',
    testing_decisions       TEXT NOT NULL DEFAULT '',
    user_stories            TEXT NOT NULL DEFAULT '',
    out_of_scope            TEXT NOT NULL DEFAULT '',

    -- Optional free-text reason a FORK was created (why this revision supersedes).
    change_reason TEXT,

    created_at    INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- A revision number is UNIQUE within its Spec.
CREATE UNIQUE INDEX idx_spec_revisions_spec_number
    ON spec_revisions (spec_id, revision_number);

-- At most ONE `active` revision per Spec: a partial unique index (only active rows
-- participate) makes a second active revision for the same Spec a constraint
-- violation, while leaving superseded history rows unconstrained on this axis.
CREATE UNIQUE INDEX idx_one_active_revision_per_spec
    ON spec_revisions (spec_id)
    WHERE revision_status = 'active';

-- Index the Spec FK for fast "revisions of this Spec" scans.
CREATE INDEX idx_spec_revisions_spec ON spec_revisions (spec_id);
