-- Schema v46: `command_slots` — the per-PROJECT binding of a graph's command SLOT.
--
-- ## The defect this closes
--
-- A `gate_check` node used to name its commands directly (`config.command_ids` = managed-command
-- instance ids). Those ids are PROJECT data — `bun test` in one repo, `cargo test -p x` in another —
-- and the node they sat on belongs to a graph SHARED by every project (the seeded built-ins). So the
-- only way to arm the shipped `coder` gate was to FORK the built-in and edit the copy, and a fork is
-- never upgraded by the boot seeder: the first gesture a real project had to make was to freeze its
-- `coder` graph at that day's revision, missing every later fix in silence.
--
-- A node in a shared graph therefore declares WHAT it needs verified (`config.slot`, e.g.
-- "build_check"), never WHICH command instance runs it; each project BINDS that slot here, to the
-- managed commands it registered. The built-in then needs no fork at all and keeps upgrading.
--
-- ## Shape
--
-- ONE row per (project, slot) — the UNIQUE index below is the whole invariant: a project answers a
-- given slot with exactly one (ordered) list of commands. `command_ids` is a JSON ARRAY of
-- `command_instances.id`, not a join table, for the same reason `nodes.config` carries its ids that
-- way: ORDER is meaningful (the gate runs them in sequence and stops at the first red) and the list
-- is read whole, never queried by element. No FK on its elements — a removed command surfaces as the
-- gate's own `invalid_id` at the tick, where the operator can read WHICH id is gone, instead of an
-- opaque cascade silently emptying a gate and making it vacuously green.
--
-- A row with an empty array reads exactly like NO row: the slot is UNBOUND, and a blocking gate on
-- an unbound slot refuses to advance (H10 — a gate that verifies nothing may not certify anything).

CREATE TABLE command_slots (
    -- UUIDv7 generated by the backend (SQLite does not auto-generate it).
    id           TEXT    NOT NULL PRIMARY KEY,

    -- The project this binding answers for. ON DELETE CASCADE: the binding is project data and
    -- has no meaning once the project is gone.
    project_id   TEXT    NOT NULL REFERENCES projects(id) ON DELETE CASCADE,

    -- The SLOT name a graph's node declares (`gate_check.config.slot`) — WHAT must be verified,
    -- in the graph author's words. Free text: nyx ships one ("build_check", the seeded coder's
    -- gate), a project-authored graph may declare its own.
    slot         TEXT    NOT NULL,

    -- The managed-command INSTANCE ids this project answers the slot with, as a JSON array
    -- (ORDER-preserving — the gate runs them in order). Default '[]' = bound to nothing.
    command_ids  TEXT    NOT NULL DEFAULT '[]',

    created_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)),
    updated_at   INTEGER NOT NULL DEFAULT (CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER))
);

-- ONE binding per (project, slot) — the upsert key, and the invariant that makes "the commands this
-- project answers that slot with" a single unambiguous read at gate time.
CREATE UNIQUE INDEX idx_command_slots_project_slot ON command_slots (project_id, slot);
